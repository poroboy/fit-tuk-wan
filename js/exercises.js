// kg moved per rep (for weekly volume)
export function loadPerRep(exId, bodyKg, dbKg) {
  const l = (EXERCISES[exId] || {}).load || {};
  if (l.bw) return l.bw * bodyKg;
  if (l.db) return l.db * dbKg;
  return 0;
}
export const isPushup = exId => exId.startsWith('pushup');
